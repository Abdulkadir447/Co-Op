async def test_products_clean(api):
    p = await preview(api, "products-clean.csv")
    assert p["row_count"] == 12
    mapping = await suggested_mapping(api, "products", "products-clean.csv")
    v = await validate(api, "products-clean.csv", "products", mapping)
    assert v["valid_rows"] == 12
    assert v["errors"] == []
    assert v["would_create"]["products"] == 12

    out = await import_file(api, "products-clean.csv", "products")
    assert out["created"]["products"] == 12
    assert out["skipped"] == {"existing": 0, "in_file": 0, "errors": 0}
    assert out["errors"] == []


async def test_customers_clean(api):
    out = await import_file(api, "customers-clean.csv", "customers")
    assert out["created"]["customers"] == 10
    assert out["errors"] == []


async def test_orders_clean_after_products_and_customers(api):
    # The realistic order: catalogue and people first, then sales history.
    products = await import_file(api, "products-clean.csv", "products")
    assert products["created"]["products"] == 12
    customers = await import_file(api, "customers-clean.csv", "customers")
    assert customers["created"]["customers"] == 10

    v = await validate(
        api, "orders-clean.csv", "orders",
        await suggested_mapping(api, "orders", "orders-clean.csv"),
    )
    assert v["valid_rows"] == 18
    assert v["errors"] == []
    assert v["unknown_refs"] == {"customers": 0, "products": 0}

    out = await import_file(api, "orders-clean.csv", "orders")
    assert out["created"]["orders"] == 18
    assert out["created"]["order_items"] == 18
    assert out["errors"] == []


async def test_reimporting_the_same_files_creates_nothing_twice(api):
    await import_file(api, "products-clean.csv", "products")
    await import_file(api, "customers-clean.csv", "customers")
    await import_file(api, "orders-clean.csv", "orders")

    again_products = await import_file(api, "products-clean.csv", "products")
    assert again_products["created"]["products"] == 0
    assert again_products["skipped"]["existing"] == 12

    again_orders = await import_file(api, "orders-clean.csv", "orders")
    assert again_orders["created"]["orders"] == 0
    assert again_orders["skipped"]["existing"] == 18



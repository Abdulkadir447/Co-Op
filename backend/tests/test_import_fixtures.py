async def test_messy_export_maps_by_alias_and_parses_naira(api):
    mapping = await suggested_mapping(api, "products", "products-messy-export.csv")
    # "Item Name" / "Selling Price" / "Qty On Hand" / "Reorder Point" are not
    # Co-op field names; the mapper has to land them anyway.
    assert mapping["Item Name"] == "name"
    assert mapping["Selling Price"] == "unit_price"
    assert mapping["Cost Price"] == "cost_price"
    assert mapping["Qty On Hand"] == "current_stock"
    assert mapping["Reorder Point"] == "reorder_level"

    out = await commit(api, "products-messy-export.csv", "products", mapping)
    assert out["created"]["products"] == 8
    assert out["errors"] == []

    products = (await api.client.get("/products", params={"limit": 100})).json()["items"]
    yam = next(p for p in products if p["name"] == "Yam tuber (large)")
    assert yam["unit_price"] == 4500.0, "₦4,500.00 must parse to 4500"
    assert yam["current_stock"] == 120


async def test_storefront_customers_without_email_get_a_placeholder(api):
    out = await import_file(api, "customers-storefront-export.csv", "customers")
    assert out["created"]["customers"] == 8

    customers = (await api.client.get("/customers", params={"limit": 100})).json()["items"]
    emails = [c["email"] for c in customers]
    assert all(emails), "every customer must end up with a usable email"
    assert len(set(emails)) == len(emails), "placeholders must not collide"
    generated = next(c for c in customers if c["full_name"] == "Ibrahim Danladi")
    assert "ibrahim" in generated["email"].lower()



"""
The import sample files in samples/imports/, driven through the real HTTP
surface the Import page uses: /imports/preview -> /imports/map ->
/imports/validate -> /imports/commit.

Two jobs:
  1. prove the samples are honest — a new user who uploads them gets exactly
     the result README.md promises, not a surprise;
  2. keep them honest — if the importer's parsers, aliases or validation
     change, these assertions fail instead of the sample files silently
     becoming misleading.

The samples are generated by samples/imports/make_fixtures.py.
"""
from __future__ import annotations

import json
import pathlib

import pytest

FIXTURES = pathlib.Path(__file__).resolve().parents[2] / "samples" / "imports"


def _read(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


async def preview(api, name: str) -> dict:
    r = await api.client.post("/imports/preview", files={"file": (name, _read(name))})
    assert r.status_code == 200, r.text
    return r.json()


async def suggested_mapping(api, entity: str, name: str) -> dict:
    """Ask /imports/map, exactly as the UI does, and keep what it matched."""
    p = await preview(api, name)
    r = await api.client.post(
        "/imports/map",
        json={"entity": entity, "headers": p["columns"], "sample_rows": p["sample_rows"]},
    )
    assert r.status_code == 200, r.text
    return {m["column"]: m["field"] for m in r.json()["mappings"] if m["field"]}


async def validate(api, name: str, entity: str, mapping: dict) -> dict:
    r = await api.client.post(
        "/imports/validate",
        files={"file": (name, _read(name))},
        data={"entity": entity, "mapping": json.dumps(mapping)},
    )
    assert r.status_code == 200, r.text
    return r.json()


async def commit(api, name: str, entity: str, mapping: dict) -> dict:
    r = await api.client.post(
        "/imports/commit",
        files={"file": (name, _read(name))},
        data={"entity": entity, "mapping": json.dumps(mapping)},
    )
    assert r.status_code == 200, r.text
    return r.json()


async def import_file(api, name: str, entity: str) -> dict:
    """The full happy path for one sample file."""
    mapping = await suggested_mapping(api, entity, name)
    return await commit(api, name, entity, mapping)


# ---------------------------------------------------------------------------
# Detection: each file has to be recognised as what it is
# ---------------------------------------------------------------------------

@pytest.mark.parametrize(
    "name,entity",
    [
        ("products-clean.csv", "products"),
        ("products-messy-export.csv", "products"),
        ("products.xlsx", "products"),
        ("customers-clean.csv", "customers"),
        ("customers-storefront-export.csv", "customers"),
        ("orders-clean.csv", "orders"),
        ("orders-accounting-export.csv", "orders"),
    ],
)
async def test_the_dataset_is_detected_from_headers_and_samples(api, name, entity):
    p = await preview(api, name)
    assert p["entity"] == entity
    assert p["entity_confidence"] > 0.4, p
    assert p["row_count"] > 0


async def test_delimiters_are_sniffed(api):
    # A wrong delimiter guess would collapse each row into one column, so
    # asserting the full header list is the real check.
    messy = await preview(api, "products-messy-export.csv")
    assert messy["columns"] == [
        "Item Name", "Item Code", "Details", "Product Category",
        "Selling Price", "Cost Price", "Qty On Hand", "Reorder Point",
    ]
    accounting = await preview(api, "orders-accounting-export.csv")
    assert accounting["columns"] == [
        "Invoice #", "Date", "Customer", "Item", "Qty", "Rate", "Amount",
    ]
    assert (await preview(api, "products.xlsx"))["fmt"] == "xlsx"


async def test_an_unsupported_extension_is_refused_before_parsing(api):
    r = await api.client.post(
        "/imports/preview", files={"file": ("notes.pdf", _read("products-clean.csv"))}
    )
    assert r.status_code == 400
    assert "Unsupported file type" in r.json()["detail"]



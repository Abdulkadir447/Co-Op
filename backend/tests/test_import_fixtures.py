async def test_products_with_errors_names_every_bad_row(api):
    mapping = await suggested_mapping(api, "products", "products-with-errors.csv")
    v = await validate(api, "products-with-errors.csv", "products", mapping)

    assert v["total_rows"] == 11
    assert v["valid_rows"] == 7
    assert len(v["errors"]) == 4
    assert v["duplicates"]["in_file"] == 1
    assert v["would_create"]["products"] == 6
    # The report has to say which rows failed, by row number.
    assert [e["row"] for e in v["errors"]] == [8, 9, 10, 11]

    out = await commit(api, "products-with-errors.csv", "products", mapping)
    assert out["created"]["products"] == 6
    assert out["skipped"]["errors"] == 4
    assert out["skipped"]["in_file"] == 1
    assert len(out["errors"]) == 4


async def test_orders_with_errors_reports_the_unknown_customer(api):
    await import_file(api, "products-clean.csv", "products")
    await import_file(api, "customers-clean.csv", "customers")

    mapping = await suggested_mapping(api, "orders", "orders-with-errors.csv")
    v = await validate(api, "orders-with-errors.csv", "orders", mapping)
    assert v["total_rows"] == 8
    assert len(v["errors"]) == 4, [e["detail"] for e in v["errors"]]
    assert v["unknown_refs"], "the ghost customer must be reported before commit"

    out = await commit(api, "orders-with-errors.csv", "orders", mapping)
    assert out["created"]["orders"] == 3
    assert out["skipped"]["errors"] == 5
    details = " ".join(e["detail"] for e in out["errors"])
    assert "ghost@example.com" in details
    assert "quantity must be at least 1" in details



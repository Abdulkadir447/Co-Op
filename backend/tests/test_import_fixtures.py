# The imported history has to be usable, not just stored
# ---------------------------------------------------------------------------

async def test_imported_history_feeds_the_reports(api):
    await import_file(api, "products-clean.csv", "products")
    await import_file(api, "customers-clean.csv", "customers")
    await import_file(api, "orders-clean.csv", "orders")

    sales = await api.client.get(
        "/reports/sales", params={"from": "2026-01-01", "to": "2026-12-31"}
    )
    assert sales.status_code == 200, sales.text
    kpis = {k["key"]: k["value"] for k in sales.json()["kpis"]}
    assert kpis["revenue"] > 0
    assert kpis["orders"] == 18
    # Totals straight off the sample file: 222 units, ₦3,603,300 across 18 lines.
    assert kpis["units"] == 222
    assert kpis["revenue"] == 3603300
